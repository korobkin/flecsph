void
interpolate_composition(double ye, double comp[COMP_GRID_LEN]) {
  ye = std::min(YE_GRID[YE_GRID_LEN-1], std::max(YE_GRID[0], ye));
  double delta_ye = YE_GRID[1] - YE_GRID[0]; // assumes uniform grid
  int jl = std::max(0,std::min((int)(ye/delta_ye), YE_GRID_LEN-2));
  int jr = jl + 1;
  double fr = ye/delta_ye - jl;
  double fl = 1. - fl;
  for(int el=0; el<COMP_GRID_LEN; el++) {
    comp[el] = COMP_GRID[el][jl]*fl + COMP_GRID[el][jr]*fr;
  }
}

